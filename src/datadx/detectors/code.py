"""Detectors for Group E: Code (E1 to E6) - used for code packs.

Enforces Rule R2: For E3 (secrets), never copy the secret value.
Evidence format is strictly '<type> at offset <offset>'. Hex is strictly empty.
"""

from __future__ import annotations

import math
import re
from collections import Counter
from typing import Any

from datadx.policy import Policy
from datadx.registry import Finding, register_detector

# Secret regex patterns
AWS_KEY_RE = re.compile(r"\bAKIA[0-9A-Z]{16}\b")
PRIVATE_KEY_RE = re.compile(r"-----BEGIN [A-Z ]*PRIVATE KEY-----")
GITHUB_TOKEN_RE = re.compile(r"\bgh[pousr]_[A-Za-z0-9_]{30,}\b")
SLACK_TOKEN_RE = re.compile(r"\bxox[abprs]-[A-Za-z0-9-]{10,}\b")
GOOGLE_API_KEY_RE = re.compile(r"\bAIza[0-9A-Za-z\-_]{35}\b")
JWT_RE = re.compile(r"\beyJ[A-Za-z0-9_-]{10,}\.[A-Za-z0-9_-]{10,}\.[A-Za-z0-9_-]{10,}\b")

# Password/token assignment regex
SECRET_ASSIGN_RE = re.compile(
    r"""(?i)(?:password|passwd|pwd|secret|token|api[_-]?key)\s*[:=]\s*['"]([^'"]{8,})['"]"""
)

# Known benign placeholders
PLACEHOLDERS = {
    "changeme",
    "password",
    "secret",
    "xxx",
    "example",
    "your_key",
    "your_token",
    "placeholder",
    "dummy",
    "admin",
}


def _shannon_entropy(s: str) -> float:
    """Calculate Shannon entropy of a string in bits/char."""
    if not s:
        return 0.0
    counts = Counter(s)
    total = len(s)
    return -sum((c / total) * math.log2(c / total) for c in counts.values())


@register_detector("E1")
def detect_e1(text: str, ctx: dict[str, Any], policy: Policy) -> list[Finding]:
    """Detect minified or auto-generated code."""
    findings: list[Finding] = []
    source = str(ctx.get("source", "")).lower()
    if "code" not in source and "code" not in str(ctx.get("lang_label", "")).lower():
        return findings

    lines = text.splitlines()
    if not lines:
        return findings

    max_len = max(len(line) for line in lines)
    mean_len = sum(len(line) for line in lines) / len(lines)
    alnum_chars = sum(1 for c in text if c.isalnum())
    alnum_ratio = alnum_chars / len(text) if text else 0.0

    header = "\n".join(lines[:10])
    is_generated = bool(
        re.search(r"(?i)auto-?generated|do not edit|generated by|@generated", header)
    )

    if max_len > 1000 or mean_len > 100 or (len(text) > 200 and alnum_ratio < 0.25) or is_generated:
        findings.append(
            Finding(
                code="E1",
                start=0,
                end=min(len(text), 100),
                kind="minified_or_generated_code",
                confidence=1.0,
                auto=True,
                note=f"max_line={max_len};mean_line={mean_len:.1f};is_gen={is_generated}",
            )
        )
    return findings


@register_detector("E2")
def detect_e2(text: str, ctx: dict[str, Any], policy: Policy) -> list[Finding]:
    """Detect data blobs (base64, hex dumps, long numeric arrays)."""
    findings: list[Finding] = []
    # Long base64 run (>= 200 chars)
    b64_matches = re.finditer(r"[A-Za-z0-9+/=]{200,}", text)
    for m in b64_matches:
        findings.append(
            Finding(
                code="E2",
                start=m.start(),
                end=m.end(),
                kind="base64_blob",
                confidence=1.0,
                auto=True,
            )
        )

    # Long hex run (>= 200 chars)
    hex_matches = re.finditer(r"[0-9a-fA-F]{200,}", text)
    for m in hex_matches:
        findings.append(
            Finding(
                code="E2",
                start=m.start(),
                end=m.end(),
                kind="hex_blob",
                confidence=1.0,
                auto=True,
            )
        )

    # Data URI
    data_uri = re.finditer(r"data:[a-z/+-]+;base64,", text)
    for m in data_uri:
        findings.append(
            Finding(
                code="E2",
                start=m.start(),
                end=m.end(),
                kind="data_uri_blob",
                confidence=1.0,
                auto=True,
            )
        )

    return findings


@register_detector("E3")
def detect_e3(text: str, ctx: dict[str, Any], policy: Policy) -> list[Finding]:
    """Detect secrets (Rule R2: stores ONLY type and offset; NEVER the secret value)."""
    findings: list[Finding] = []

    patterns = [
        ("AWS key", AWS_KEY_RE),
        ("private key", PRIVATE_KEY_RE),
        ("GitHub token", GITHUB_TOKEN_RE),
        ("Slack token", SLACK_TOKEN_RE),
        ("Google API key", GOOGLE_API_KEY_RE),
        ("JWT token", JWT_RE),
    ]

    for label, pattern in patterns:
        for match in pattern.finditer(text):
            # Rule R2: Store only type and offset. Matched string dropped immediately.
            offset = match.start()
            end = match.end()
            findings.append(
                Finding(
                    code="E3",
                    start=offset,
                    end=end,
                    kind=label,  # "AWS key", "private key", etc.
                    confidence=1.0,
                    auto=True,
                    hex_repr="",  # Rule R2: strictly empty
                )
            )

    # High-entropy secret assignments
    for match in SECRET_ASSIGN_RE.finditer(text):
        val = match.group(1)
        # Drop placeholders
        if val.lower() in PLACEHOLDERS or val.startswith(("<", "${")) or val.endswith(">"):
            continue
        entropy = _shannon_entropy(val)
        if len(val) >= 8 and entropy >= 3.5:
            offset = match.start()
            end = match.end()
            findings.append(
                Finding(
                    code="E3",
                    start=offset,
                    end=end,
                    kind="high entropy secret",
                    confidence=0.9,
                    auto=True,
                    hex_repr="",  # Rule R2: strictly empty
                )
            )

    return findings


@register_detector("E4")
def detect_e4(text: str, ctx: dict[str, Any], policy: Policy) -> list[Finding]:
    """Repeated license headers in code packs."""
    findings: list[Finding] = []
    lines = text.splitlines()[:40]
    header_text = "\n".join(lines)

    if any(
        phrase in header_text
        for phrase in [
            "SPDX-License-Identifier",
            "Licensed under",
            "Permission is hereby granted",
            "Copyright (c)",
        ]
    ):
        findings.append(
            Finding(
                code="E4",
                start=0,
                end=min(len(text), len(header_text)),
                kind="license_header",
                confidence=0.85,
                auto=True,
            )
        )
    return findings


