"""Unit tests for Group E detectors (E1 to E6).

Enforces Rule R2: For E3 (secrets), never stores secret value.
"""

from datadx.detectors.code import detect_e1, detect_e2, detect_e3
from datadx.policy import load_policy

POLICY = load_policy()


def test_e1_minified_or_generated():
    ctx = {"source": "code", "lang_label": "code_python"}
    text = "# @generated by tool\n" + "x = 1\n" * 10
    findings = detect_e1(text, ctx, POLICY)
    assert len(findings) == 1
    assert findings[0].code == "E1"


def test_e2_data_blob():
    # Base64 run >= 200 chars
    b64_blob = "A" * 250
    text = f"const data = '{b64_blob}';"
    findings = detect_e2(text, {}, POLICY)
    assert len(findings) == 1
    assert findings[0].code == "E2"


def test_e3_secrets_rule_r2_privacy():
    # AWS Key: AKIA followed by 16 chars
    text = "aws_access_key = 'AKIA1234567890ABCDEF'"
    findings = detect_e3(text, {}, POLICY)
    assert len(findings) == 1
    f = findings[0]
    assert f.code == "E3"
    assert f.kind == "AWS key"
    assert f.hex_repr == ""  # Rule R2: hex is empty

    # format_evidence must be type + offset ONLY
    ev = f.format_evidence(text)
    assert ev == f"AWS key at offset {f.start}"
    assert "AKIA" not in ev  # Value never leaked
